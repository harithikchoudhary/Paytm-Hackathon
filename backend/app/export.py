import json
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from .samples import pdf_bytes, policy_pdf
from .policies import POLICY_ID, CLAUSES
from .customer import policy_context


def packet(app):
    context = policy_context(app)
    summary = pdf_bytes('Reviewed preliminary reimbursement packet' if app.get('issued_policy') else 'Reviewed reimbursement packet', [
        f"Application: {app['title']}", f"Application ID: {app['id']}",
        f"Reviewed at: {app['reviewed_at']}", f"Policy reference: {context['id']}", '',
        *[f"{f['label']}: {f['value']}" for f in app['fields'].values() if f['value']], '',
        'Reviewer notes:', *[i['message'] for i in app['issues']], '',
        'Checklist completion only. This packet does not establish coverage, payout, or insurer approval.',
        'Check the full insurer document list and conditional requirements before actual submission.' if app.get('issued_policy') else 'All included sample documents and rules are synthetic.',
    ])
    body = BytesIO()
    with ZipFile(body, 'w', ZIP_DEFLATED) as z:
        z.writestr('claim-summary.pdf', summary)
        if app.get('issued_policy'):
            z.writestr('policy-source-reference.json', json.dumps(context, indent=2))
        else:
            z.writestr('trusted-synthetic-policy.pdf', policy_pdf())
        z.writestr('claim-data.json', json.dumps({
            'id': app['id'], 'reviewed_at': app['reviewed_at'], 'revision': app['revision'],
            'policy_id': context['id'], 'issued_policy': app.get('issued_policy'), 'fields': app['fields'], 'reviewer_notes': app['issues'],
            'audit': app['audit'], 'clauses': context['clauses'],
        }, indent=2))
        for doc in app['documents']:
            # Storage paths are generated by the server, never derived from user filenames.
            z.writestr(f"documents/{doc['kind']}-{doc['id']}{Path(doc['path']).suffix}", Path(doc['path']).read_bytes())
    return body.getvalue()
